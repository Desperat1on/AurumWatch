"""AurumWatch——国内金价与国际金价的阈值监视与弹窗提醒。

模块职责：

- `alerts`（触发判定核心）、`failures`（取数故障记账）、`viewmodel`（主窗口
  视图模型）、`schedule`（刷新节奏）：纯函数层——不碰网络、Tk 与终端，窗口
  要显示什么由它们算，怎么摆由窗口决定。
- `config`：配置的默认值、规范化与校验是纯函数；`load`／`save` 是它的副作用
  部分（读写 config.json、原子替换）。
- `journal`：事件 → 文字的构造与「哪些旧日志该清」是纯函数；`Journal` 是它的
  副作用部分（写当天的日志文件、内存里留最近 50 条事件记录）。
- `theme`：当前外观——用户调的那几项（配色、字体、基准字号……）与由它们派生的
  配色、字号档位，主窗口、设置窗口与弹窗都从这里取。
- `quotes`（取数与解析）、`popup`（弹窗与提示音）、`main_window`（主窗口）、
  `settings_window`（设置窗口）、`single_instance`（命名互斥体）、`autostart`
  （开机自启的注册表读写）：副作用层。
- `app`：编排——主窗口、设置窗口、轮询线程、提醒、事件记录与视图模型的接线。

可调项只在 `config.json` 与设置窗口里，源码中没有配置区（见 ticket 03）。
双击「启动金价监视.bat」运行（等价于 `python -m aurumwatch`）；关闭主窗口即退出监视。
"""

